/**
 * Onboarding Screen 1 (spec 7) - the shape of a new business workspace.
 *
 * Shared deliberately, exactly as `@/lib/auth/schemas` is: the Phase 4C-3 form
 * will use these rules for inline feedback and the server re-parses the same
 * schema before touching the database. The browser is never trusted, so
 * client-side validation is a convenience and the server parse is the control.
 *
 * **No submitted value is ever echoed back in a message.** A rejected
 * workspace name or country code is the submitter's data; naming the field is
 * enough to fix it, and repeating the value puts it into logs and error
 * surfaces where it does not belong.
 */

/**
 * C0 and C1 control characters, plus DEL.
 *
 * Rejected rather than stripped, everywhere. A newline in a business name is
 * far more likely to be an injection attempt against some later renderer than
 * part of a real name, and silently repairing it would hide that. The database
 * routine applies the same rule as a backstop.
 */
const CONTROL_CHARACTERS = /[\u0000-\u001F\u007F-\u009F]/;

const noControlCharacters = <T extends z.ZodType<string>>(
  schema: T,
  field: string,
) =>
  schema.refine((value) => !CONTROL_CHARACTERS.test(value), {
    message: `Remove the special characters from the ${field}`,
  });

