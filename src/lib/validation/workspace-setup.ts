const TIME_ZONE_SET: ReadonlySet<string> = new Set(TIME_ZONES);

/** Exact, case-sensitive membership - the same comparison the trigger makes. */
export const isSupportedTimeZone = (value: string): boolean =>
  TIME_ZONE_SET.has(value);

/** The fields a setup submission may contain, plus the form-level bucket. */
export type WorkspaceSetupField =
  | "fullName"
  | "workspaceName"
  | "businessType"
  | "country"
  | "currency"
  | "timeZone"
  | "form";

export type WorkspaceSetupIssue = {
  readonly field: WorkspaceSetupField;
  readonly message: string;
};

/**
 * The submission.
 *
 * `strictObject`, so an unknown key is an error rather than something quietly
 * dropped. That is the point: a payload carrying `authUserId`, `workspaceId`,
 * `role` or `status` must be refused loudly, because whoever built it believed
 * those fields would be honoured.
 */
export const workspaceSetupSchema = z.strictObject({
  /** Profile display data only - never identity, never authorisation. */
  fullName: noControlCharacters(fullNameSchema, "name"),

  workspaceName: noControlCharacters(
    z
      .string({ message: "Enter your business name" })
      .trim()
      .min(2, "Enter your business name")
      .max(160, "That business name is too long"),
    "business name",
  ),

  /**
   * Optional (7), free text, and deliberately not an enum: 7 calls its eight
   * values "examples" and states the choice "should not lock the CRM into an
   * industry". Absent, empty and whitespace-only all become null, so the
   * column never holds an empty string.
   */
  businessType: noControlCharacters(
    z
      .string({ message: "That business type is not valid" })
      .trim()
      .max(120, "That business type is too long"),
    "business type",
  )
    .nullish()
    .transform((value) => (value == null || value === "" ? null : value)),

  country: z
    .string({ message: "Select a country" })
    .trim()
    .transform((value) => value.toUpperCase())
    .refine((value) => COUNTRY_SET.has(value), {
      message: "Select a country from the list",
    }),

  currency: z
    .string({ message: "Select a currency" })
    .trim()
    .transform((value) => value.toUpperCase())
    .refine((value) => CURRENCY_SET.has(value), {
      message: "Select a currency from the list",
    }),

  timeZone: z
    .string({ message: "Select a time zone" })
    .trim()
    .max(100, "That time zone is too long")
    .refine(isSupportedTimeZone, {
      message: "Select a time zone from the list",
    }),
});

/** The normalized values, ready for the database routine. */
export type WorkspaceSetupInput = z.output<typeof workspaceSetupSchema>;

export type WorkspaceSetupResult =
  | { readonly ok: true; readonly value: WorkspaceSetupInput }
  | { readonly ok: false; readonly issues: readonly WorkspaceSetupIssue[] };

const FIELDS: readonly WorkspaceSetupField[] = [
  "fullName",
  "workspaceName",
  "businessType",
  "country",
  "currency",
  "timeZone",
];

const fieldOf = (path: readonly PropertyKey[]): WorkspaceSetupField => {
  const head = path[0];
  return typeof head === "string" &&
    (FIELDS as readonly string[]).includes(head)
    ? (head as WorkspaceSetupField)
    : "form";
};

/**
 * Parse a submission into normalized values, or a frozen list of issues.
 *
 * Never throws, and never puts a submitted value into an issue message.
 */
export function parseWorkspaceSetup(input: unknown): WorkspaceSetupResult {
  const parsed = workspaceSetupSchema.safeParse(input);
  if (parsed.success) {
    return Object.freeze({ ok: true, value: Object.freeze(parsed.data) });
  }

  const seen = new Set<string>();
  const issues: WorkspaceSetupIssue[] = [];
  for (const issue of parsed.error.issues) {
    const field = fieldOf(issue.path as readonly PropertyKey[]);
    const key = field + ":" + issue.message;
    if (seen.has(key)) continue;
    seen.add(key);
    issues.push(Object.freeze({ field, message: issue.message }));
  }

  return Object.freeze({ ok: false, issues: Object.freeze(issues) });
}
